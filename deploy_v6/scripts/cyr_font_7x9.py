"""
Embedded 7x9 pixel font for Russian uppercase + digits + punctuation.

No external dependencies — every glyph is hard-coded as a 9-row tuple of
7-bit bitmasks. This avoids the "система не нашла шрифт" failure mode
when running in a sandbox without TTF files.

Each glyph row is 7 bits wide, MSB = leftmost pixel. Row 0 is the top.
Empty rows above/below the visual glyph are kept for baseline alignment.

Usage:
    from cyr_font_7x9 import render_text
    img = render_text("МЕНЮ", color=(255,255,255), shadow=(0,0,0), scale=2)
"""

from PIL import Image

# ---------------------------------------------------------------------------
# Glyph table. Each entry: 9 rows of 7 bits (LSB->MSB drawn left->right).
# To visually edit, treat each row as a 7-character string of "#" and "." and
# convert with int(s.replace('.', '0').replace('#', '1'), 2).
# ---------------------------------------------------------------------------

def _g(*rows):
    """Build a glyph from 9 strings of length 7 using '#' for filled."""
    assert len(rows) == 9, f"expected 9 rows, got {len(rows)}"
    out = []
    for r in rows:
        assert len(r) == 7, f"row must be 7 chars, got {len(r)}: {r!r}"
        out.append(int(r.replace('.', '0').replace('#', '1'), 2))
    return tuple(out)


